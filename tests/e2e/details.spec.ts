import { expect, test, type Page } from '@playwright/test'
async function post(page: Page, path: string, data: unknown = {}) {
  return page.evaluate(async ({ path, data }) => {
    const response = await fetch(`/api/${path}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) })
    if (!response.ok) throw new Error(`Fixture request failed: ${response.status}`)
    return response.json()
  }, { path, data })
}
async function session(page: Page, userId: string) {
  const response = await post(page, 'demo/details/session', { userId }) as { token: string }
  await page.evaluate(token => localStorage.setItem('kurio.session-token', token), response.token)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Favoritar', exact: true }).or(page.getByRole('button', { name: 'Remover dos favoritos', exact: true }))).toBeEnabled()
}
