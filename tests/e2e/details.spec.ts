test('favorite optimism rolls back on failure, persists and isolates identities', async ({ page }) => {
  await page.goto('/nfts/emerald-ape')
  await expect(page.getByRole('heading', { name: 'Emerald Ape #042', exact: true })).toBeVisible()
  await session(page, 'ana')
  await post(page, 'demo/favorites/fail-next')
  await page.getByRole('button', { name: 'Favoritar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Remover dos favoritos', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('alert')).toContainText('Estado anterior restaurado')
  await expect(page.getByRole('button', { name: 'Favoritar', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Favoritar', exact: true }).click()
  await expect(page.getByText('Favoritos atualizados.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Remover dos favoritos', exact: true })).toBeEnabled()
  await session(page, 'bruno')
  await expect(page.getByRole('button', { name: 'Favoritar', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await session(page, 'ana')
  await page.getByRole('button', { name: 'Remover dos favoritos', exact: true }).click()
  await expect(page.getByText('Favoritos atualizados.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Favoritar', exact: true })).toHaveAttribute('aria-pressed', 'false')
})
