test('expiry during optimistic mutation clears private state and prevents delayed write', async ({ page }) => {
  await page.goto('/nfts/emerald-ape?edition=ten&quantity=2')
  await expect(page.getByRole('button', { name: 'Favoritar', exact: true })).toBeVisible()
  await session(page, 'ana')
  await post(page, 'demo/favorites/hold')
  const write = page.waitForRequest(request => request.url().endsWith('/api/favorites/emerald-ape') && request.method() === 'PUT')
  await page.getByRole('button', { name: 'Favoritar', exact: true }).click()
  await write
  await expect(page.getByRole('button', { name: 'Remover dos favoritos', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await post(page, 'demo/details/expire')
  await expect.poll(() => page.evaluate(() => localStorage.getItem('kurio.session-token'))).toBeNull()
  await expect(page.getByRole('button', { name: 'Favoritar', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await session(page, 'ana')
  await expect(page.getByRole('button', { name: 'Favoritar', exact: true })).toHaveAttribute('aria-pressed', 'false')
})
