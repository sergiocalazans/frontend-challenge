import { expect, test } from '@playwright/test'
import { loginViaApi } from './auth-helpers'

async function credentials(page: import('@playwright/test').Page, email = 'ana@example.com', password = 'Collector123!') {
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill(email)
  await page.getByLabel(/^Senha/).fill(password)
  await page.getByRole('button', { name: 'Entrar', exact: true }).last().click()
}
test('login restores protected context, refresh, logout and another user', async ({ page }) => {
  const loadedSession = page.waitForResponse(response => new URL(response.url()).pathname === '/api/session' && response.request().method() === 'GET')
  await page.goto('/account/profile?tab=details')
  expect((await loadedSession).status()).toBe(200)
  await expect(page).toHaveURL(/login.*returnTo/)
  await credentials(page, 'ana@example.com', 'incorrect')
  await expect(page.getByRole('alert')).toContainText('E-mail ou senha incorretos')
  await credentials(page)
  await expect(page).toHaveURL('/account/profile?tab=details')
  await expect(page.getByRole('button', { name: 'Sair', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/login/)
  await credentials(page, 'bruno@example.com')
  await expect(page).toHaveURL('/account/profile?tab=details')
  const user = await page.evaluate(async () => (await (await fetch('/api/session', { headers: { Authorization: `Bearer ${localStorage.getItem('kurio.session-token')}` } })).json()).user)
  expect(user.id).toBe('bruno')
})
