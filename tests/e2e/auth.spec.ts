test('stale logout cannot clear the newer session created in another tab', async ({ page, context }) => {
  await loginViaApi(page)
  await page.goto('/account/profile')
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
  const scenario = (action: string) => page.evaluate(async action => { await fetch('/api/demo/auth', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action }) }) }, action)
  await scenario('hold-logout')
  const sent = page.waitForRequest(request => request.url().endsWith('/api/session') && request.method() === 'DELETE')
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await sent
  const other = await context.newPage()
  await loginViaApi(other, 'bruno@example.com')
  const newerToken = await other.evaluate(() => localStorage.getItem('kurio.session-token'))
  await scenario('release-logout')
  await expect(page.getByRole('button', { name: 'Sair', exact: true })).toBeEnabled()
  await expect(page).toHaveURL('/account/profile')
  expect(await page.evaluate(() => localStorage.getItem('kurio.session-token'))).toBe(newerToken)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
  const userId = await page.evaluate(async () => (await (await fetch('/api/session', { headers: { Authorization: `Bearer ${localStorage.getItem('kurio.session-token')}` } })).json()).user.id)
  expect(userId).toBe('bruno')
})

test('visitor logs in from favorite intent, preserves edition and isolates favorites after switching users', async ({ page }) => {
  const target = '/nfts/emerald-ape?edition=ten&quantity=2'
  await page.goto(target)
  await page.getByRole('button', { name: 'Favoritar', exact: true }).click()
  await expect(page).toHaveURL(/login.*returnTo=/)
  await credentials(page)
  await expect(page).toHaveURL(target)
  await expect(page.getByRole('radio', { name: '1/10', exact: true })).toBeChecked()
  await expect(page.getByRole('group', { name: 'Quantidade', exact: true })).toContainText('2')
  await page.getByRole('button', { name: 'Favoritar', exact: true }).click()
  await expect(page.getByText('Favoritos atualizados.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Remover dos favoritos', exact: true })).toBeEnabled()
  await page.goto('/account/profile')
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/login/)
  await credentials(page, 'bruno@example.com')
  await page.goto(target)
  await expect(page.getByRole('button', { name: 'Favoritar', exact: true })).toHaveAttribute('aria-pressed', 'false')
})
