import { expect, test } from '@playwright/test'

async function credentials(page: import('@playwright/test').Page, email = 'ana@example.com', password = 'Collector123!') {
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill(email)
  await page.getByLabel(/^Senha/).fill(password)
  await page.getByRole('button', { name: 'Entrar', exact: true }).last().click()
}
test('login restores protected context, refresh, logout and another user', async ({ page }) => {
  await page.goto('/account/profile?tab=details')
  await expect(page).toHaveURL(/login.*returnTo/)
  await credentials(page, 'ana@example.com', 'incorrect')
  await expect(page.getByRole('alert')).toContainText('E-mail ou senha incorretos')
  await credentials(page)
  await expect(page).toHaveURL('/account/profile?tab=details')
  await expect(page.getByRole('button', { name: 'Sair', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/login/)
  await credentials(page, 'bruno@example.com')
  await expect(page).toHaveURL('/account/profile?tab=details')
  const user = await page.evaluate(async () => (await (await fetch('/api/session', { headers: { Authorization: `Bearer ${localStorage.getItem('kurio.session-token')}` } })).json()).user)
  expect(user.id).toBe('bruno')
})
test('registration validates, persists and reports API conflict', async ({ page }) => {
  await page.goto('/register?returnTo=%2Faccount%2Fwallets')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page.getByLabel('Nome de usuário')).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Nome de usuário').fill('Nova Colecionadora')
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill('ana@example.com')
  await page.getByLabel(/^Senha/).fill('Example123!')
  await page.getByLabel('Confirmar senha').fill('different')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page.getByLabel('Confirmar senha')).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('Confirmar senha').fill('Example123!')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'E-mail', exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill('nova@example.com')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page).toHaveURL('/account/wallets')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Carteiras', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('kurio.mock-auth.v1'))).not.toContain('Example123!')
})
test('expiry preserves protected context and recovery; safe return target', async ({ page }) => {
  await page.goto('/login?returnTo=%2Fcheckout%3Fstep%3Dreview')
  await credentials(page)
  await expect(page).toHaveURL('/checkout?step=review')
  await page.evaluate(async () => { await fetch('/api/demo/auth', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'expire' }) }) })
  await page.reload()
  await expect(page).toHaveURL(/login.*returnTo/)
  await credentials(page)
  await expect(page).toHaveURL('/checkout?step=review')
  await page.goto('/login?returnTo=%2F%2Fevil.example')
  await credentials(page)
  await expect(page).toHaveURL('/')
})
test('slow submission prevents duplicate operations and server error recovers', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill('ana@example.com')
  await page.getByLabel(/^Senha/).fill('Collector123!')
  const scenario = async (action: string) => page.evaluate(async action => { await fetch('/api/demo/auth', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action }) }) }, action)
  await scenario('error')
  await page.getByRole('button', { name: 'Entrar', exact: true }).last().click()
  await expect(page.getByRole('alert')).toContainText('Serviço indisponível')
  await scenario('slow')
  await page.getByRole('button', { name: 'Entrar', exact: true }).last().click()
  await expect(page.getByRole('button', { name: 'Aguarde…' })).toBeDisabled()
  await expect(page).toHaveURL('/')
})
