import { test, expect } from '@playwright/test'
import { loginViaApi } from './auth-helpers'

test('catalog loads through MSW and restores search after refresh', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('nft-emerald-ape')).toContainText('1.19 ETH')
  await page.getByRole('textbox', { name: 'Buscar NFTs' }).fill('Golden')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(page).toHaveURL(/q=Golden/)
  await expect(page.getByTestId('nft-golden-beat')).toBeVisible()
  await expect(page.getByTestId('nft-emerald-ape')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Buscar NFTs' })).toHaveValue('Golden')
  await expect(page.getByTestId('nft-golden-beat')).toBeVisible()
})

test('dialog traps focus, closes with Escape, and restores focus', async ({ page }) => {
  await page.goto('/design-system')
  const trigger = page.getByRole('button', { name: 'Abrir modal', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Detalhes da demonstração' })
  await expect(dialog).toBeVisible()
  await expect(page.getByLabel('Nome de exibição')).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Fechar', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Nome de exibição')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})

test('validates fields, quantity limits and filter drawer', async ({ page }) => {
  await page.goto('/design-system')
  await page.getByRole('button', { name: 'Validar campo' }).click()
  await expect(page.getByLabel('E-mail')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByText('Informe um e-mail válido.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Diminuir quantidade' })).toBeDisabled()
  for (let i = 0; i < 4; i++) await page.getByRole('button', { name: 'Aumentar quantidade' }).click()
  await expect(page.getByRole('button', { name: 'Aumentar quantidade' })).toBeDisabled()
  await page.getByRole('button', { name: 'Abrir filtros' }).click()
  await page.getByRole('dialog').getByLabel('Rede').selectOption('Polygon')
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('nft-sage-nomad')).toBeVisible()
  await expect(page.getByTestId('nft-emerald-ape')).toHaveCount(0)
})

test('renders slow, empty and error network scenarios, then recovers', async ({ page }) => {
  await page.goto('/design-system')
  await expect(page.getByTestId('nft-emerald-ape')).toBeVisible()
  const scenario = page.getByLabel('Cenário MSW')
  await scenario.selectOption('slow')
  await expect(page.getByRole('status', { name: 'Carregando NFTs' })).toBeVisible()
  await expect(page.getByTestId('nft-emerald-ape')).toBeVisible()
  await expect(scenario).toBeEnabled()
  await scenario.selectOption('empty')
  await expect(page.getByText('Nenhum NFT encontrado', { exact: true })).toBeVisible()
  await expect(scenario).toBeEnabled()
  await scenario.selectOption('error')
  await expect(page.getByRole('alert')).toContainText('temporariamente indisponível')
  await expect(scenario).toBeEnabled()
  await scenario.selectOption('default')
  await expect(page.getByTestId('nft-emerald-ape')).toBeVisible()
})

